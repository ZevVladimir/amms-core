"""
Sanity cehck on an IC file and then record the results next to that file

Usage:
    amms ic-sanity IC.hdf5 [--params GEN.parameters] [--generator makegalaxy]
                            [--upstream sha256.txt] [--gridded] [--dry-run]

Writes  <ic_dir>/sanity/<ic_stem>/{fingerprint.yaml, checks.yaml}
Links   $AMMS_PRODUCTS/ics/<ic_dir name> -> <ic_dir>/sanity
Prints  a Markdown table used for Obsidian

Currently
    Makegalaxy is currently the only generator
    --gridded only relaxes the gas count (grid step actually changes it) not the gas mass
"""

from __future__ import annotations

import argparse
import dataclasses
from pathlib import Path

from amms.core import ics
from amms.core._yamlio import dump_record, write_atomic
from amms.core.checks import Status, worst
from amms.core.codes import makegalaxy
from amms.core.config.paths import products_root

# Generator modules expose read_parameters(path) and component_budget(params)
GENERATORS = {"makegalaxy": makegalaxy}
HEADER = "Generated by ic_sanity.py. Do NOT hand-edit instead re-run amms ic-sanity to regenerate"


def fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.6g}"
    if isinstance(v, str) and len(v) == 64:  # sha256: keeps table readable
        return v[:12] + "..."
    return "" if v is None else str(v)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="amms ic-sanity")
    ap.add_argument("ic", type=Path)
    ap.add_argument("--params", type=Path, help="generator output parameters, for the budget")
    ap.add_argument("--generator", default="makegalaxy", choices=GENERATORS)
    ap.add_argument(
        "--upstream", type=Path, help="sha256sum record; default: <ic_dir>/sha256.txt if present"
    )
    ap.add_argument("--gridded", action="store_true", help="IC went through the AREPO grid step")
    ap.add_argument("--dry-run", action="store_true", help="print only, write nothing")
    a = ap.parse_args(argv)

    ic = a.ic.resolve()
    fp = ics.fingerprint(ic)
    results = []

    if a.upstream and not a.upstream.exists():
        ap.error(f"--upstream {a.upstream} does not exist")
    upstream = a.upstream or (ic.parent / "sha256.txt")
    if upstream.exists():
        results.append(ics.check_upstream_hash(fp, upstream))

    if a.params:
        gen = GENERATORS[a.generator]
        budget = gen.component_budget(gen.read_parameters(a.params))
        if a.gridded:
            # Grid step turns N gas particles into a different number of cells. But mass must survive
            budget = [dataclasses.replace(c, n=None) if c.ptype == 0 else c for c in budget]
        masses = ics.component_masses(ic, fp.header)
        results += ics.check_mass_budget(fp.header, masses, budget)

    if not results:
        print(f"**{fp.name}**: NO CHECKS RUN (no --params, no sha256.txt). Fingerprint only")

    status = worst(results) if results else Status.WARN
    print(f"**{fp.name}**: {status.value} (sha256 {fp.sha256[:12]}...)\n")
    print("| Check | Status | Value | Expected | Detail |\n|---|---|---|---|---|")
    for r in results:
        print(f"| {r.name} | {r.status.value} | {fmt(r.value)} | {fmt(r.expected)} | {r.detail} |")

    if a.dry_run:
        return

    out = ic.parent / "sanity" / ic.stem
    out.mkdir(parents=True, exist_ok=True)
    write_atomic(out / "fingerprint.yaml", dump_record(fp.to_dict(), HEADER))
    # sha256 comes along so a stale product (e.g. IC overwritten with same name) is detectable
    record = {
        "ic_sha256": fp.sha256,
        "status": status.value,
        "checks": [r.to_dict() for r in results],
    }
    write_atomic(out / "checks.yaml", dump_record(record, HEADER))

    link = products_root() / "ics" / ic.parent.name
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink() or link.exists():
        if link.resolve() != (ic.parent / "sanity").resolve():
            print(f"\nWARNING: {link} exists and points elsewhere; left unchanged")
    else:
        link.symlink_to(ic.parent / "sanity")


if __name__ == "__main__":
    main()
