"""
Pins dump_record: the do-not-edit header is present and the body round-trips to the same data,
including the shapes IC fingerprints actually contain (tuples, int keys, nested dicts).
"""

import yaml

from amms.core._yamlio import dump_record


def test_dump_record_header_and_roundtrip():
    data = {
        "sha256": "ab" * 32,
        "header": {"num_part": (3, 2, 0), "datasets": {0: {"Coordinates": "float32"}}},
        "checks": [{"name": "mass_type0", "status": "pass", "value": 6.0, "expected": None}],
    }
    text = dump_record(data, "Generated by test.\nDo NOT hand-edit")
    assert text.startswith("# Generated by test.\n# Do NOT hand-edit\n")

    back = yaml.safe_load(text)
    assert back["header"]["num_part"] == [3, 2, 0]  # tuples come back as lists
    assert back["header"]["datasets"] == {0: {"Coordinates": "float32"}}  # int keys survive
    assert back["checks"] == data["checks"]
    assert back["sha256"] == data["sha256"]
